/** Model of user credentials */
type Credentials = {
    /** The email/phone the user logged in with */
    login?: string;

    /** The password the user logged in with */
    password?: string;

    twoFactorAuthCode?: string;
    validateCode?: string;

    /** The short-lived authToken issued when a 2FA code is required */
    authToken?: string;

    autoGeneratedLogin?: string;
    autoGeneratedPassword?: string;
    accountID?: number;

    /** The user's ID for external integration */
    partnerUserID?: string;

    /** The user's secret for external integration */
    partnerUserSecret?: string;
};

export default Credentials;
