/**
 * Details page for an Integration Server API login, opened from the contact methods list. These logins can't be
 * validated or set as default, so the only action is removing the login, which revokes the API's access.
 */
import FullPageNotFoundView from '@components/BlockingViews/FullPageNotFoundView';
import {useDelegateNoAccessActions, useDelegateNoAccessState} from '@components/DelegateNoAccessModalProvider';
import HeaderWithBackButtonAndTitle from '@components/Header/composed/HeaderWithBackButtonAndTitle';
import MenuItemAction from '@components/MenuItem/presets/MenuItemAction';
import {ModalActions} from '@components/Modal/Global/ModalContext';
import OfflineWithFeedback from '@components/OfflineWithFeedback';
import ScreenWrapper from '@components/ScreenWrapper';
import ScrollView from '@components/ScrollView';
import Text from '@components/Text';

import useConfirmModal from '@hooks/useConfirmModal';
import useDynamicBackPath from '@hooks/useDynamicBackPath';
import {useMemoizedLazyExpensifyIcons} from '@hooks/useLazyAsset';
import useLocalize from '@hooks/useLocalize';
import useOnyx from '@hooks/useOnyx';
import useThemeStyles from '@hooks/useThemeStyles';

import {clearRevokeError, revokeDevice} from '@libs/actions/User';
import Navigation from '@libs/Navigation/Navigation';
import type {PlatformStackScreenProps} from '@libs/Navigation/PlatformStackNavigation/types';
import type {SettingsNavigatorParamList} from '@libs/Navigation/types';
import {getLoginKey, integrationServerLoginsSelector} from '@libs/UserUtils';

import CONST from '@src/CONST';
import ONYXKEYS from '@src/ONYXKEYS';
import {DYNAMIC_ROUTES} from '@src/ROUTES';
import type SCREENS from '@src/SCREENS';

import autoGeneratedLoginSelector from '@selectors/Credentials';
import React from 'react';

type DynamicIntegrationServerLoginDetailsPageProps = PlatformStackScreenProps<SettingsNavigatorParamList, typeof SCREENS.SETTINGS.PROFILE.DYNAMIC_INTEGRATION_SERVER_LOGIN_DETAILS>;

function DynamicIntegrationServerLoginDetailsPage({route}: DynamicIntegrationServerLoginDetailsPageProps) {
    const styles = useThemeStyles();
    const {translate} = useLocalize();
    const icons = useMemoizedLazyExpensifyIcons(['Trashcan']);
    const [integrationServerLogins] = useOnyx(ONYXKEYS.LOGINS, {selector: integrationServerLoginsSelector});
    const [autoGeneratedLogin] = useOnyx(ONYXKEYS.CREDENTIALS, {selector: autoGeneratedLoginSelector});
    const {isActingAsDelegate} = useDelegateNoAccessState();
    const {showDelegateNoAccessModal} = useDelegateNoAccessActions();
    const {showConfirmModal} = useConfirmModal();
    const listPath = useDynamicBackPath(DYNAMIC_ROUTES.INTEGRATION_SERVER_LOGIN_DETAILS.path);

    const login = integrationServerLogins?.find((integrationServerLogin) => integrationServerLogin.partnerUserID === route.params.partnerUserID);

    const removeLogin = async () => {
        if (!login) {
            return;
        }
        if (isActingAsDelegate) {
            showDelegateNoAccessModal();
            return;
        }

        const result = await showConfirmModal({
            title: translate('contacts.removeContactMethod'),
            prompt: translate('contacts.removeAreYouSure'),
            confirmText: translate('common.yesContinue'),
            cancelText: translate('common.cancel'),
            shouldShowCancelButton: true,
            buttonVariant: CONST.BUTTON_VARIANT.DANGER,
        });
        if (result.action !== ModalActions.CONFIRM) {
            return;
        }

        revokeDevice(login, autoGeneratedLogin);
        Navigation.goBack(listPath);
    };

    if (!login) {
        return (
            <ScreenWrapper testID="DynamicIntegrationServerLoginDetailsPage">
                <FullPageNotFoundView
                    shouldShow
                    linkTranslationKey="contacts.goBackContactMethods"
                    onBackButtonPress={() => Navigation.goBack(listPath)}
                    onLinkPress={() => Navigation.goBack(listPath)}
                />
            </ScreenWrapper>
        );
    }

    return (
        <ScreenWrapper testID="DynamicIntegrationServerLoginDetailsPage">
            <HeaderWithBackButtonAndTitle
                title={translate('contacts.integrationServerLogin.title')}
                onBackButtonPress={() => Navigation.goBack(listPath)}
            />
            <ScrollView contentContainerStyle={styles.flexGrow1}>
                <Text style={[styles.ph5, styles.mv3]}>{translate('contacts.integrationServerLogin.removeDescription')}</Text>
                <OfflineWithFeedback
                    pendingAction={login.pendingAction}
                    errors={login.errorFields?.revoke}
                    errorRowStyles={[styles.mt6, styles.ph5]}
                    onClose={() => clearRevokeError(getLoginKey(login))}
                >
                    <MenuItemAction
                        title={translate('common.remove')}
                        icon={icons.Trashcan}
                        onPress={removeLogin}
                    />
                </OfflineWithFeedback>
            </ScrollView>
        </ScreenWrapper>
    );
}

export default DynamicIntegrationServerLoginDetailsPage;
