import CONST from '@src/CONST';
import {getCurrentUserEmail} from '@src/libs/CurrentUserStore';
import Log from '@src/libs/Log';
import ONYXKEYS from '@src/ONYXKEYS';
import type Credentials from '@src/types/onyx/Credentials';

import type {ValueOf} from 'type-fest';

// TODO: Rename this module to AuthStore in a follow-up PR — it only manages auth/credentials state now.
import Onyx from 'react-native-onyx';

let credentials: Credentials | null | undefined;
let lastShortAuthToken: string | null | undefined;
let authToken: string | null | undefined;
let authTokenType: ValueOf<typeof CONST.AUTH_TOKEN_TYPES> | null;
let accountID: number | null | undefined;
let authenticating = false;

type AuthTokenDrop = {
    source: 'setAuthToken' | 'session';
    droppedAt: number;
    stack?: string;
};

let lastAuthTokenDrop: AuthTokenDrop | undefined;

const AUTH_TOKEN_DROP_STACK_FRAMES = 8;

let resolveIsReadyPromise: (args?: unknown[]) => void;
let isReadyPromise = new Promise((resolve) => {
    resolveIsReadyPromise = resolve;
});

/**
 * This is a hack to workaround the fact that Onyx may not yet have read these values from storage by the time Network starts processing requests.
 * If the values are undefined we haven't read them yet. If they are null or have a value then we have and the network is "ready".
 */
function checkRequiredData() {
    if (authToken === undefined || credentials === undefined) {
        return;
    }

    resolveIsReadyPromise();
}

function resetHasReadRequiredDataFromStorage() {
    // Create a new promise and a new resolve function
    isReadyPromise = new Promise((resolve) => {
        resolveIsReadyPromise = resolve;
    });
}

// Use connectWithoutView since this doesn't affect to any UI
Onyx.connectWithoutView({
    key: ONYXKEYS.SESSION,
    callback: (val) => {
        const newAuthToken = val?.authToken ?? null;
        if (authToken && !newAuthToken) {
            lastAuthTokenDrop = {source: 'session', droppedAt: Date.now()};
            Log.warn('[NetworkStore] authToken dropped', {source: 'session', hasEmail: !!val?.email, accountID: val?.accountID});
        }
        authToken = newAuthToken;
        authTokenType = val?.authTokenType ?? null;
        accountID = val?.accountID ?? null;
        checkRequiredData();
    },
});

// Use connectWithoutView since this doesn't affect to any UI
Onyx.connectWithoutView({
    key: ONYXKEYS.CREDENTIALS,
    callback: (val) => {
        Log.info('[NetworkStore] Updating credentials', false, {autoGeneratedLogin: !!val?.autoGeneratedLogin, autoGeneratedPassword: !!val?.autoGeneratedPassword});
        credentials = val ?? null;
        checkRequiredData();
    },
});

function getCredentials(): Credentials | null | undefined {
    return credentials;
}

function getAuthToken(): string | null | undefined {
    return authToken;
}

function getAccountID(): number | null | undefined {
    return accountID;
}

function getLastShortAuthToken(): string | null | undefined {
    return lastShortAuthToken;
}

function setLastShortAuthToken(newLastAuthToken: string | null) {
    lastShortAuthToken = newLastAuthToken;
}

function isSupportAuthToken(): boolean {
    return authTokenType === CONST.AUTH_TOKEN_TYPES.SUPPORT;
}

function setAuthToken(newAuthToken: string | null) {
    if (authToken && !newAuthToken) {
        const stack = new Error().stack?.split('\n').slice(0, AUTH_TOKEN_DROP_STACK_FRAMES).join('\n');
        lastAuthTokenDrop = {source: 'setAuthToken', droppedAt: Date.now(), stack};
        Log.warn('[NetworkStore] authToken dropped', {source: 'setAuthToken', stack});
    }
    authToken = newAuthToken;
}

function getLastAuthTokenDrop(): AuthTokenDrop | undefined {
    return lastAuthTokenDrop;
}

function hasReadRequiredDataFromStorage(): Promise<unknown> {
    return isReadyPromise;
}

function isAuthenticating(): boolean {
    return authenticating;
}

function setIsAuthenticating(val: boolean) {
    authenticating = val;
}

export {
    getAuthToken,
    getAccountID,
    setAuthToken,
    getCurrentUserEmail,
    hasReadRequiredDataFromStorage,
    resetHasReadRequiredDataFromStorage,
    isAuthenticating,
    setIsAuthenticating,
    getCredentials,
    checkRequiredData,
    isSupportAuthToken,
    getLastShortAuthToken,
    setLastShortAuthToken,
    getLastAuthTokenDrop,
};
