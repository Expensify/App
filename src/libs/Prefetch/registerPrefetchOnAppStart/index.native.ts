/**
 * Registers a native startup prefetch (and its Authenticate token-refresh config) with
 * `react-native-nitro-fetch` so whitelisted API requests can be fetched before the JS bundle loads.
 */
import {AUTHENTICATION_COMMAND} from '@libs/API/types';
import {getCommandURL} from '@libs/ApiUtils';
import Log from '@libs/Log';
import {getBaseRequestParameters} from '@libs/Network/enhanceParameters';
import isJWTAuthToken from '@libs/Network/isJWTAuthToken';
import {getCredentials} from '@libs/Network/NetworkStore';
import {getPartnerCredentials} from '@libs/SessionUtils';

import CONST from '@src/CONST';
import type Credentials from '@src/types/onyx/Credentials';

import {clearTokenRefresh, prefetchOnAppStart, registerTokenRefresh} from 'react-native-nitro-fetch';

import type RegisterPrefetchOnAppStart from './types';

const NITRO_FETCH_TARGET = 'fetch';
const CONTENT_TYPE_HEADER = 'Content-Type';

type PrefetchFormData = {
    getParts: () => Array<{fieldName: string; string: string}>;
};

function buildAuthenticateBody(credentials: Credentials): string {
    // NitroFetch token refresh runs outside the JS request pipeline, so we must serialize the
    // Authenticate body here instead of going through Request.post() and enhanceParameters().
    const {partnerName, partnerPassword} = getPartnerCredentials(credentials.autoGeneratedLogin);

    // The `appversion` parameter is omitted intentionally here.
    // This is because it can cause issues during app updates and
    // it is not needed by the "Authenticate" command for token refresh.
    // eslint-disable-next-line @typescript-eslint/naming-convention
    const {referer, platform, api_setCookie, isFromDevEnv} = getBaseRequestParameters();

    const body = new URLSearchParams();
    body.append('useExpensifyLogin', 'false');
    body.append('partnerName', partnerName);
    body.append('partnerPassword', partnerPassword);
    body.append('partnerUserID', credentials.autoGeneratedLogin ?? '');
    body.append('partnerUserSecret', credentials.autoGeneratedPassword ?? '');
    body.append('shouldRetry', 'false');
    body.append('forceNetworkRequest', 'true');
    body.append('email', credentials.login ?? '');
    body.append('referer', referer);
    body.append('platform', platform);
    body.append('api_setCookie', String(api_setCookie));
    body.append('isFromDevEnv', String(isFromDevEnv));

    return body.toString();
}

function isPrefetchFormData(body: unknown): body is PrefetchFormData {
    return typeof body === 'object' && body !== null && 'getParts' in body && typeof body.getParts === 'function';
}

/**
 * The saved body can be replayed natively on the next app start, which may already be running a newer version after an update.
 * Sending the old `appversion` there would get a 426 and show the Update Required screen, so it is omitted.
 */
function removeAppVersionFromPrefetchBody(body: RequestInit['body']): RequestInit['body'] {
    if (!isPrefetchFormData(body)) {
        return body;
    }

    // React Native's own `FormData` type leaves `fieldName` out of the parts, so read them through our narrower type.
    const prefetchFormData: PrefetchFormData = body;
    const prefetchBody = new FormData();
    for (const part of prefetchFormData.getParts()) {
        if (part.fieldName === 'appversion') {
            continue;
        }
        prefetchBody.append(part.fieldName, part.string);
    }
    return prefetchBody;
}

function getPrefetchAuthToken(body: RequestInit['body']): string | undefined {
    if (!isPrefetchFormData(body)) {
        return undefined;
    }

    const prefetchFormData: PrefetchFormData = body;
    return prefetchFormData.getParts().find((part) => part.fieldName === CONST.HTTP_HEADER_NAMES.AUTH_TOKEN)?.string;
}

/**
 * Nitro maps every refreshed token into the header without looking at it, so the Authorization mapping is only registered when the saved request
 * carries a JWT. If Auth refreshes it to a hex token, the prefetch sends that as a Bearer header until the app saves a ReconnectApp sent with a hex token.
 */
function registerPrefetchTokenRefresh(shouldMapAuthorizationHeader: boolean): void {
    const credentials = getCredentials();

    clearTokenRefresh(NITRO_FETCH_TARGET);

    if (!credentials?.autoGeneratedLogin || !credentials.autoGeneratedPassword) {
        return;
    }

    const authenticateURL = `${getCommandURL({command: AUTHENTICATION_COMMAND})}`;

    registerTokenRefresh({
        target: NITRO_FETCH_TARGET,
        url: authenticateURL,
        method: 'POST',
        headers: {
            [CONTENT_TYPE_HEADER]: 'application/x-www-form-urlencoded',
        },
        body: buildAuthenticateBody(credentials),
        responseType: 'json',
        mappings: shouldMapAuthorizationHeader
            ? [{jsonPath: CONST.HTTP_HEADER_NAMES.AUTH_TOKEN, header: CONST.HTTP_HEADER_NAMES.AUTHORIZATION, valueTemplate: 'Bearer {{value}}'}]
            : undefined,
        formDataMappings: [{jsonPath: CONST.HTTP_HEADER_NAMES.AUTH_TOKEN, field: CONST.HTTP_HEADER_NAMES.AUTH_TOKEN}],
        onFailure: 'useStoredHeaders',
    });

    Log.info('[NitroFetchTokenRefresh] Registered token refresh for startup prefetch', false);
}

const registerPrefetchOnAppStart: RegisterPrefetchOnAppStart = ({prefetchKey, fetchParams, command, url}) => {
    if (!prefetchKey) {
        return;
    }

    registerPrefetchTokenRefresh(isJWTAuthToken(getPrefetchAuthToken(fetchParams.body)));
    prefetchOnAppStart(url, {...fetchParams, body: removeAppVersionFromPrefetchBody(fetchParams.body)}).catch((error) => {
        Log.warn(`[NitroFetch] prefetchOnAppStart failed for ${command}`, {error, fetchParams, url});
    });
};

export default registerPrefetchOnAppStart;
