// This entry is selected only by the emulator evaluation builds, never by index.js. It runs the normal app first.
import '../index';
import type {Connection, OnyxEntry} from 'react-native-onyx';

import HybridAppModule from '@expensify/react-native-hybrid-app';
import {Platform} from 'react-native';
import RNFS from 'react-native-fs';
import Onyx from 'react-native-onyx';

import type {Session} from './types/onyx';

import {EMULATOR_SIGN_IN_ERROR_FILE, EMULATOR_SIGN_IN_FILE, needsEmulatorSignIn, parseEmulatorSignIn} from '../scripts/pgo/emulatorSignIn';
import CONFIG from './CONFIG';
import {setReadyToShowAuthScreens, setUseNewDotSignInPage} from './libs/actions/HybridApp';
import {AUTHENTICATION_COMMAND} from './libs/API/types';
import {post} from './libs/Network';
import {getPartnerCredentials} from './libs/SessionUtils';
import ONYXKEYS from './ONYXKEYS';

const signInDirectory = Platform.OS === 'android' ? RNFS.ExternalDirectoryPath : RNFS.DocumentDirectoryPath;
// HybridApp checks the launch settings from native within seconds. Sign in anyway if they never arrive.
const HYBRID_APP_LAUNCH_TIMEOUT_MS = 60_000;

/** Sign a disposable emulator into the CI test account, which nobody can sign into by hand there. */
async function signInForEmulatorEvaluation(): Promise<void> {
    const signInPath = `${signInDirectory}/${EMULATOR_SIGN_IN_FILE}`;
    if (!(await RNFS.exists(signInPath))) {
        return;
    }
    const signIn = parseEmulatorSignIn(JSON.parse(await RNFS.readFile(signInPath, 'utf8')));
    if (!needsEmulatorSignIn(await readStoredSession(), signIn.email, Date.now())) {
        return;
    }
    // At launch, HybridApp clears a session that Expensify Classic does not share. Sign in only after that check.
    await waitForHybridAppLaunch();
    const partner = signIn.partnerName && signIn.partnerPassword ? {partnerName: signIn.partnerName, partnerPassword: signIn.partnerPassword} : getPartnerCredentials(signIn.partnerUserID);
    const response = await post(AUTHENTICATION_COMMAND, {
        useExpensifyLogin: false,
        ...partner,
        partnerUserID: signIn.partnerUserID,
        partnerUserSecret: signIn.partnerUserSecret,
        email: signIn.email,
        shouldRetry: false,
        forceNetworkRequest: true,
    });
    if (Number(response.jsonCode) !== 200 || !response.authToken) {
        throw new Error(`Authenticate returned jsonCode ${String(response.jsonCode)}.`);
    }
    // New Expensify stores only the session. Signing out sends CREDENTIALS.autoGeneratedLogin to LogOut, which would revoke the shared CI login for every later run.
    // eslint-disable-next-line rulesdir/prefer-actions-set-data -- This CI-only entry is not part of the app, and no app action stores a partner-login session.
    await Onyx.merge(ONYXKEYS.CREDENTIALS, {login: signIn.email});
    // eslint-disable-next-line rulesdir/prefer-actions-set-data -- See above.
    await Onyx.merge(ONYXKEYS.SESSION, {
        authToken: response.authToken,
        encryptedAuthToken: response.encryptedAuthToken,
        accountID: response.accountID,
        email: signIn.email,
        creationDate: Date.now(),
    });
    if (!CONFIG.IS_HYBRID_APP) {
        return;
    }
    // Finish the sign-in the way HybridApp does after a New Expensify sign-in, so Classic shares the session on every later launch.
    HybridAppModule.signInToOldDot({
        autoGeneratedLogin: signIn.partnerUserID,
        autoGeneratedPassword: signIn.partnerUserSecret,
        authToken: response.authToken,
        email: signIn.email,
        policyID: '',
    });
    await setUseNewDotSignInPage(false);
    setReadyToShowAuthScreens(true);
}

function readStoredSession(): Promise<OnyxEntry<Session>> {
    return new Promise((resolve) => {
        // This CI entry runs outside any view and reads the persisted session once.
        const connection = Onyx.connectWithoutView({
            key: ONYXKEYS.SESSION,
            callback: (session) => {
                Onyx.disconnect(connection);
                resolve(session);
            },
        });
    });
}

/** OldDot stamps the settings of every launch, so a new timestamp means this launch's HybridApp check has finished. */
function waitForHybridAppLaunch(): Promise<void> {
    if (!CONFIG.IS_HYBRID_APP) {
        return Promise.resolve();
    }
    let connection: Connection | undefined;
    let timeout: ReturnType<typeof setTimeout> | undefined;
    return new Promise<void>((resolve) => {
        let previousLaunch: number | undefined;
        let hasReadStoredValue = false;
        timeout = setTimeout(resolve, HYBRID_APP_LAUNCH_TIMEOUT_MS);
        // This CI entry runs outside any view and waits for one HybridApp value.
        connection = Onyx.connectWithoutView({
            key: ONYXKEYS.HYBRID_APP,
            callback: (hybridApp) => {
                if (!hasReadStoredValue) {
                    hasReadStoredValue = true;
                    previousLaunch = hybridApp?.transitionStartTimestamp;
                    return;
                }
                if (hybridApp?.transitionStartTimestamp !== undefined && hybridApp.transitionStartTimestamp !== previousLaunch) {
                    resolve();
                }
            },
        });
    }).finally(() => {
        clearTimeout(timeout);
        if (connection) {
            Onyx.disconnect(connection);
        }
    });
}

signInForEmulatorEvaluation().catch((error: unknown) => {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[PGO CI] Emulator sign-in failed: ${message}`);
    // Release builds may drop console output, so leave the reason where the runner reads it after a failed sign-in.
    RNFS.writeFile(`${signInDirectory}/${EMULATOR_SIGN_IN_ERROR_FILE}`, message, 'utf8').catch(() => undefined);
});
