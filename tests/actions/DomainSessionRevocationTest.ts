import {
    dismissDomainSessionRevocation,
    getDomainSessionRevocationStatus,
    revokeAllDomainMemberSessions,
    revokeDomainMemberSessions,
    updateDomainSessionRevocationStatus,
} from '@libs/actions/Domain';
import redirectToSignIn from '@libs/actions/SignInRedirect';
import * as API from '@libs/API';
import {SIDE_EFFECT_REQUEST_COMMANDS} from '@libs/API/types';
import generateSessionRevocationHandle from '@libs/generateSessionRevocationHandle';
import Navigation from '@libs/Navigation/Navigation';
import * as Network from '@libs/Network';
import {setHasRadio} from '@libs/NetworkState';
import reauthenticate from '@libs/Reauthentication';

import CONST from '@src/CONST';
import IntlStore from '@src/languages/IntlStore';
import ONYXKEYS from '@src/ONYXKEYS';
import type Response from '@src/types/onyx/Response';

import Onyx from 'react-native-onyx';

import getOnyxValue from '../utils/getOnyxValue';
import waitForBatchedUpdates from '../utils/waitForBatchedUpdates';

jest.mock('@libs/Navigation/Navigation', () => ({resetToAppRoot: jest.fn()}));
jest.mock('@libs/generateSessionRevocationHandle', () => jest.fn(() => 'ab'.repeat(32)));

const completionHandle = 'ab'.repeat(32);
let request: jest.SpiedFunction<typeof API.makeRequestWithSideEffects>;

describe('Domain session revocation actions', () => {
    beforeAll(() => Onyx.init({keys: ONYXKEYS}));
    beforeEach(async () => {
        jest.restoreAllMocks();
        jest.clearAllMocks();
        request = jest.spyOn(API, 'makeRequestWithSideEffects').mockResolvedValue({jsonCode: 200});
        IntlStore.load(CONST.LOCALES.EN);
        setHasRadio(true);
        await Onyx.clear();
        await waitForBatchedUpdates();
    });

    it('targets one account, waits for its response, and prevents a repeated click', async () => {
        // Given a pending revocation response for a phone-primary member
        const pending = Promise.withResolvers<Response<never>>();
        request.mockReturnValue(pending.promise);

        // When the action is invoked twice before the server replies
        const first = revokeDomainMemberSessions(10, 20);
        expect(await revokeDomainMemberSessions(10, 20)).toBe(false);
        await waitForBatchedUpdates();

        // Then one non-replaying request targets the account ID and remains pending until confirmed
        expect(request).toHaveBeenCalledTimes(1);
        expect(request).toHaveBeenCalledWith(SIDE_EFFECT_REQUEST_COMMANDS.REVOKE_DOMAIN_MEMBER_SESSIONS, {
            domainAccountID: 10,
            targetAccountID: 20,
            shouldRetry: false,
            skipReauthentication: true,
        });
        expect(await getOnyxValue(`${ONYXKEYS.COLLECTION.DOMAIN_PENDING_ACTIONS}10`)).toBeFalsy();
        pending.resolve({jsonCode: 200, selfRevoked: false, revokedAccountCount: 1});
        expect(await first).toBe(true);
    });

    it('clears local credentials only after confirmed self-revocation', async () => {
        // Given an admin revoking their own sessions
        await Onyx.set(ONYXKEYS.SESSION, {accountID: 20, authToken: 'old-token'});
        await Onyx.set(ONYXKEYS.CREDENTIALS, {autoGeneratedLogin: 'saved-login', autoGeneratedPassword: 'saved-password'});
        request.mockResolvedValue({jsonCode: 200, selfRevoked: true, revokedAccountCount: 1});

        // When the server confirms self-revocation
        expect(await revokeDomainMemberSessions(10, 20)).toBe(true);

        // Then neither the current token nor saved credentials remain
        expect((await getOnyxValue(ONYXKEYS.SESSION))?.authToken).toBeFalsy();
        expect((await getOnyxValue(ONYXKEYS.CREDENTIALS))?.autoGeneratedPassword).toBeFalsy();
    });

    it('shows a failure instead of treating a lost member response as success', async () => {
        // Given an indeterminate network response
        request.mockResolvedValue({jsonCode: CONST.JSON_CODE.UNABLE_TO_RETRY});

        // When the member action finishes without confirmation
        const succeeded = await revokeDomainMemberSessions(10, 20);

        // Then the member retains a visible error and the pending state ends
        expect(succeeded).toBe(false);
        expect((await getOnyxValue(`${ONYXKEYS.COLLECTION.DOMAIN_ERRORS}10`))?.memberErrors?.[20]?.revokeSessionsErrors).toBeTruthy();
        expect(await getOnyxValue(`${ONYXKEYS.COLLECTION.DOMAIN_PENDING_ACTIONS}10`)).toBeFalsy();
    });

    it('does not queue security actions while offline', async () => {
        // Given an offline device
        setHasRadio(false);

        // When either action is attempted
        await revokeDomainMemberSessions(10, 20);
        await revokeAllDomainMemberSessions(10);

        // Then neither a request nor a receipt is queued for later submission
        expect(request).not.toHaveBeenCalled();
        expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toBeFalsy();
    });

    it('persists the receipt before submission and recovers a lost response without resubmitting', async () => {
        // Given a start response that is lost after the job has been accepted
        request.mockImplementation(async () => {
            expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toEqual({completionHandle, status: 'running'});
            throw new Error('Connection lost');
        });

        // When submission fails and the user attempts the action again
        await revokeAllDomainMemberSessions(10);
        await revokeAllDomainMemberSessions(10);

        // Then the same capability is used to look up the original job instead of starting another
        expect(request).toHaveBeenCalledTimes(1);
        expect(request).toHaveBeenCalledWith(SIDE_EFFECT_REQUEST_COMMANDS.REVOKE_ALL_DOMAIN_MEMBER_SESSIONS, {
            domainAccountID: 10,
            completionHandle,
            shouldRetry: false,
            skipReauthentication: true,
        });
        request.mockResolvedValue({jsonCode: 200, status: 'succeeded'});
        expect(await getDomainSessionRevocationStatus(completionHandle)).toBe('succeeded');
        expect(request).toHaveBeenLastCalledWith(SIDE_EFFECT_REQUEST_COMMANDS.GET_DOMAIN_SESSION_REVOCATION_STATUS, {
            completionHandle,
            shouldRetry: false,
            skipReauthentication: true,
        });
        expect(generateSessionRevocationHandle).toHaveBeenCalledTimes(1);
    });

    it('preserves completion through ordinary and SAML cleanup without preserving credentials', async () => {
        // Given a running receipt while the worker revokes the actor
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        await Onyx.set(ONYXKEYS.SESSION, {accountID: 20, email: 'admin@example.com', authToken: 'old-token'});
        await Onyx.set(ONYXKEYS.CREDENTIALS, {autoGeneratedLogin: 'saved-login', autoGeneratedPassword: 'saved-password', validateCode: '123456'});
        await waitForBatchedUpdates();

        // When ordinary reauthentication requests a SAML redirect, then completion arrives
        await redirectToSignIn(CONST.SIGN_OUT_REASON.SAML_REQUIRED, undefined, true);
        expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toEqual({completionHandle, status: 'running'});
        await updateDomainSessionRevocationStatus(completionHandle, 'succeeded');

        // Then completion survives all cleanup and Return to sign-in is only local navigation
        expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toEqual({completionHandle, status: 'succeeded'});
        expect((await getOnyxValue(ONYXKEYS.SESSION))?.authToken).toBeFalsy();
        expect(await getOnyxValue(ONYXKEYS.CREDENTIALS)).toBeFalsy();
        await dismissDomainSessionRevocation();
        expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toBeFalsy();
        expect(request).not.toHaveBeenCalled();
        expect(Navigation.resetToAppRoot).toHaveBeenCalledTimes(1);
    });

    it.each(['failed', 'unavailable'] as const)('does not reinterpret %s as a successful sign-out', async (status) => {
        // Given a terminal result that does not establish domain-wide success
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        await Onyx.set(ONYXKEYS.SESSION, {authToken: 'still-valid'});
        request.mockResolvedValue({jsonCode: 200, status});

        // When the result is retrieved and saved
        await updateDomainSessionRevocationStatus(completionHandle, await getDomainSessionRevocationStatus(completionHandle));

        // Then the honest outcome is saved and no successful local logout is inferred
        expect((await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION))?.status).toBe(status);
        expect((await getOnyxValue(ONYXKEYS.SESSION))?.authToken).toBe('still-valid');
    });

    it('does not use saved credentials to reauthenticate while completion is visible', async () => {
        // Given a restored receipt and ordinary saved credentials
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        await Onyx.set(ONYXKEYS.SESSION, {authToken: 'expired-token'});
        await Onyx.set(ONYXKEYS.CREDENTIALS, {autoGeneratedLogin: 'saved-login', autoGeneratedPassword: 'saved-password'});
        await waitForBatchedUpdates();
        const authenticate = jest.spyOn(Network, 'post').mockResolvedValue({jsonCode: 200});

        // When an unrelated request encounters the revoked token
        const result = await reauthenticate('OpenApp');

        // Then no authentication request is sent and the receipt survives local cleanup
        expect(result.wasSuccessful).toBe(false);
        expect(authenticate).not.toHaveBeenCalled();
        expect(await getOnyxValue(ONYXKEYS.CREDENTIALS)).toBeFalsy();
        expect((await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION))?.status).toBe('running');
    });
});
