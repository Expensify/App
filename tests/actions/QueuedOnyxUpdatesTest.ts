import {flushQueue, getInFlightFlushPromise, queueOnyxUpdates} from '@libs/actions/QueuedOnyxUpdates';

import type {OnyxKey} from '@src/ONYXKEYS';
import ONYXKEYS from '@src/ONYXKEYS';

import type {OnyxUpdate} from 'react-native-onyx';

import Onyx from 'react-native-onyx';

import waitForBatchedUpdates from '../utils/waitForBatchedUpdates';

const queuedOnyxUpdates: Array<
    OnyxUpdate<
        | typeof ONYXKEYS.NVP_TRY_FOCUS_MODE
        | typeof ONYXKEYS.PREFERRED_THEME
        | typeof ONYXKEYS.NVP_PREFERRED_LOCALE
        | typeof ONYXKEYS.SESSION
        | typeof ONYXKEYS.IS_LOADING_APP
        | typeof ONYXKEYS.CREDENTIALS
        | typeof ONYXKEYS.RAM_ONLY_IS_SIDEBAR_LOADED
        | typeof ONYXKEYS.COLLECTION.REPORT
        | typeof ONYXKEYS.COLLECTION.REPORT_ACTIONS
    >
> = [
    {key: ONYXKEYS.NVP_TRY_FOCUS_MODE, value: true, onyxMethod: 'merge'},
    {key: ONYXKEYS.PREFERRED_THEME, value: 'system', onyxMethod: 'merge'},
    {key: ONYXKEYS.NVP_PREFERRED_LOCALE, value: 'en', onyxMethod: 'merge'},
    {
        key: ONYXKEYS.SESSION,
        value: {
            accountID: 18748326,
            authToken: 'testToken',
            email: 'abcd+2342424224@gmail.com',
            encryptedAuthToken: 'testEncryptedAuthToken',
            loading: false,
        },
        onyxMethod: 'merge',
    },
    {key: ONYXKEYS.IS_LOADING_APP, value: false, onyxMethod: 'merge'},
    {
        key: ONYXKEYS.CREDENTIALS,
        value: {
            autoGeneratedLogin: '',
            autoGeneratedPassword: '',
            login: 'abcd+2342424224@gmail.com',
        },
        onyxMethod: 'merge',
    },
    {key: ONYXKEYS.RAM_ONLY_IS_SIDEBAR_LOADED, value: true, onyxMethod: 'merge'},
    {key: `${ONYXKEYS.COLLECTION.REPORT}2175919089355165`, value: {reportID: 'reportID'}, onyxMethod: 'merge'},
    {
        key: `${ONYXKEYS.COLLECTION.REPORT_ACTIONS}2175919089355165`,
        value: {
            // eslint-disable-next-line @typescript-eslint/naming-convention
            '4135522899867010163': {
                reportActionID: '4135522899867010163',
            },
        },
        onyxMethod: 'merge',
    },
];

jest.mock('@src/CONFIG', () => ({
    IS_TEST_ENV: false,
}));

// QueuedOnyxUpdates now imports Log, which transitively pulls in the network stack that reads
// the (mocked, partial) CONFIG at load time. Mock Log so that chain never loads.
jest.mock('@libs/Log');

function getOnyxUpdateValue(key: string) {
    return queuedOnyxUpdates.find((item) => item.key === key)?.value;
}

async function testOnyxKeyValue(key: OnyxKey): Promise<void> {
    const expectedValue = getOnyxUpdateValue(key);
    return new Promise<void>((resolve) => {
        const connection = Onyx.connect({
            key,
            callback: (value) => {
                Onyx.disconnect(connection);

                expect(value).toEqual(expectedValue);
                resolve();
            },
        });
    });
}

describe('actions/QueuedOnyxUpdates', () => {
    beforeAll(() => {
        Onyx.init({
            keys: ONYXKEYS,
        });
    });

    beforeEach(() => {
        return Onyx.clear().then(waitForBatchedUpdates);
    });

    describe('flushQueue', () => {
        it('should filter queued updates when currentAccountID is undefined', async () => {
            await queueOnyxUpdates(queuedOnyxUpdates);
            await Onyx.multiSet({
                [ONYXKEYS.SESSION]: null,
            });

            await flushQueue();

            await testOnyxKeyValue(ONYXKEYS.NVP_TRY_FOCUS_MODE);
            await testOnyxKeyValue(ONYXKEYS.PREFERRED_THEME);
            await testOnyxKeyValue(ONYXKEYS.NVP_PREFERRED_LOCALE);
            await testOnyxKeyValue(ONYXKEYS.SESSION);
            await testOnyxKeyValue(ONYXKEYS.IS_LOADING_APP);
            await testOnyxKeyValue(ONYXKEYS.CREDENTIALS);
            await testOnyxKeyValue(ONYXKEYS.RAM_ONLY_IS_SIDEBAR_LOADED);

            await new Promise<void>((resolve) => {
                const connection = Onyx.connect({
                    key: `${ONYXKEYS.COLLECTION.REPORT}2175919089355165`,
                    callback: (report) => {
                        Onyx.disconnect(connection);
                        expect(report).toBeUndefined();

                        resolve();
                    },
                });
            });

            await new Promise<void>((resolve) => {
                const connection = Onyx.connect({
                    key: `${ONYXKEYS.COLLECTION.REPORT_ACTIONS}2175919089355165`,
                    callback: (report) => {
                        Onyx.disconnect(connection);
                        expect(report).toBeUndefined();

                        resolve();
                    },
                });
            });
        });

        it('should not filter updates if currentAccountID is defined', async () => {
            await queueOnyxUpdates(queuedOnyxUpdates);
            await Onyx.multiSet({
                [ONYXKEYS.SESSION]: {
                    accountID: 1,
                },
            });

            await flushQueue();

            await testOnyxKeyValue(ONYXKEYS.NVP_TRY_FOCUS_MODE);
            await testOnyxKeyValue(ONYXKEYS.PREFERRED_THEME);
            await testOnyxKeyValue(ONYXKEYS.NVP_PREFERRED_LOCALE);
            await testOnyxKeyValue(ONYXKEYS.SESSION);
            await testOnyxKeyValue(ONYXKEYS.IS_LOADING_APP);
            await testOnyxKeyValue(ONYXKEYS.CREDENTIALS);
            await testOnyxKeyValue(ONYXKEYS.RAM_ONLY_IS_SIDEBAR_LOADED);

            await new Promise<void>((resolve) => {
                const connection = Onyx.connect({
                    key: `${ONYXKEYS.COLLECTION.REPORT}2175919089355165`,
                    callback: (report) => {
                        Onyx.disconnect(connection);
                        expect(report).toEqual(getOnyxUpdateValue(`${ONYXKEYS.COLLECTION.REPORT}2175919089355165`));

                        resolve();
                    },
                });
            });

            await new Promise<void>((resolve) => {
                const connection = Onyx.connect({
                    key: `${ONYXKEYS.COLLECTION.REPORT_ACTIONS}2175919089355165`,
                    callback: (reportActions) => {
                        Onyx.disconnect(connection);
                        expect(reportActions).toEqual(getOnyxUpdateValue(`${ONYXKEYS.COLLECTION.REPORT_ACTIONS}2175919089355165`));

                        resolve();
                    },
                });
            });
        });
    });

    describe('getInFlightFlushPromise', () => {
        it('returns the flush promise only while its storage write is still running', async () => {
            // Given a staged update and a signed-in session
            await Onyx.merge(ONYXKEYS.SESSION, {accountID: 1});
            await queueOnyxUpdates([{key: ONYXKEYS.NVP_TRY_FOCUS_MODE, value: true, onyxMethod: 'merge'}]);

            // When the flush starts, the staged array is already empty but the write is still in flight
            const flush = flushQueue();
            expect(getInFlightFlushPromise()).toBe(flush);

            // Then it is cleared once the write settles
            await flush;
            expect(getInFlightFlushPromise()).toBeNull();
        });

        it('keeps a newer flush in flight when an older one settles first', async () => {
            // Given the first flush's storage write is held open
            await Onyx.merge(ONYXKEYS.SESSION, {accountID: 1});
            const realUpdate = Onyx.update.bind(Onyx);
            let releaseFirstFlush: (() => void) | undefined;
            let releaseSecondFlush: (() => void) | undefined;
            const updateSpy = jest
                .spyOn(Onyx, 'update')
                .mockImplementationOnce(
                    (updates) =>
                        new Promise<void>((resolve) => {
                            releaseFirstFlush = () => {
                                realUpdate(updates).then(resolve);
                            };
                        }),
                )
                .mockImplementationOnce(
                    (updates) =>
                        new Promise<void>((resolve) => {
                            releaseSecondFlush = () => {
                                realUpdate(updates).then(resolve);
                            };
                        }),
                );
            await queueOnyxUpdates([{key: ONYXKEYS.NVP_TRY_FOCUS_MODE, value: true, onyxMethod: 'merge'}]);
            const firstFlush = flushQueue();

            // When a second flush starts before the first settles, and the first settles first
            await queueOnyxUpdates([{key: ONYXKEYS.PREFERRED_THEME, value: 'system', onyxMethod: 'merge'}]);
            const secondFlush = flushQueue();
            releaseFirstFlush?.();
            await firstFlush;

            // Then the second flush is still reported as in flight, since catch-up responses must keep waiting on it
            expect(getInFlightFlushPromise()).toBe(secondFlush);

            releaseSecondFlush?.();
            await secondFlush;
            updateSpy.mockRestore();
            expect(getInFlightFlushPromise()).toBeNull();
        });
    });
});
