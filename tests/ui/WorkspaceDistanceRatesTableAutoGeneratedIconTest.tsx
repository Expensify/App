import {act, render, screen} from '@testing-library/react-native';

import ComposeProviders from '@components/ComposeProviders';
import {LocaleContextProvider} from '@components/LocaleContextProvider';
import {ModalProvider} from '@components/Modal/Global/ModalContext';
import OnyxListItemProvider from '@components/OnyxListItemProvider';
import ScreenWrapperStatusContext from '@components/ScreenWrapper/ScreenWrapperStatusContext';
import WorkspaceDistanceRatesTable from '@components/Tables/WorkspaceDistanceRatesTable';
import type {DistanceRateTableItemData} from '@components/Tables/WorkspaceDistanceRatesTable/WorkspaceDistanceRatesTableRow';

import {CurrentReportIDContextProvider} from '@hooks/useCurrentReportID';
import * as useResponsiveLayoutModule from '@hooks/useResponsiveLayout';
import type ResponsiveLayoutResult from '@hooks/useResponsiveLayout/types';

import CONST from '@src/CONST';
import ONYXKEYS from '@src/ONYXKEYS';
import type {Rate} from '@src/types/onyx/Policy';

import {PortalProvider} from '@gorhom/portal';
import {NavigationContainer} from '@react-navigation/native';
import React from 'react';
import Onyx from 'react-native-onyx';

import * as TestHelper from '../utils/TestHelper';
import waitForBatchedUpdatesWithAct from '../utils/waitForBatchedUpdatesWithAct';

const WIDE_LAYOUT: ResponsiveLayoutResult = {
    shouldUseNarrowLayout: false,
    isSmallScreenWidth: false,
    isInNarrowPaneModal: false,
    isExtraSmallScreenHeight: false,
    isMediumScreenWidth: false,
    isLargeScreenWidth: true,
    isExtraLargeScreenWidth: false,
    isExtraSmallScreenWidth: false,
    isSmallScreen: false,
    onboardingIsMediumOrLargerScreenWidth: true,
    isInLandscapeMode: false,
};

const SCREEN_WRAPPER_STATUS = {didScreenTransitionEnd: true, isSafeAreaTopPaddingApplied: true, isSafeAreaBottomPaddingApplied: true};

const POLICY_ID = 'policy-1';

/** A rate that still matches the government snapshot it was copied from. */
const GOVERNMENT_RATE: Rate = {
    customUnitRateID: 'irs',
    name: 'IRS',
    rate: 7000,
    currency: CONST.CURRENCY.USD,
    enabled: true,
    startDate: '2026-01-01',
    attributes: {governmentRate: {sourceRateID: 'US_2026-01-01', rate: 7000, startDate: '2026-01-01'}},
};

function buildRow(rate: Rate): DistanceRateTableItemData {
    return {
        keyForList: rate.customUnitRateID,
        rateID: rate.customUnitRateID,
        rate,
        formattedRate: '$0.70 / mile',
        formattedTaxReclaimable: '',
        enabled: true,
        isLocked: false,
        canEditName: false,
        canEditRate: false,
        canEditTaxReclaimable: false,
        action: jest.fn(),
        dismissError: jest.fn(),
        onToggleEnabled: jest.fn(),
        onRenameName: jest.fn(),
        onChangeRate: jest.fn(),
        onChangeTaxReclaimable: jest.fn(),
    };
}

function buildTable(isGovernmentRateAutoUpdateEnabled: boolean) {
    return (
        <ComposeProviders components={[OnyxListItemProvider, LocaleContextProvider, CurrentReportIDContextProvider]}>
            <PortalProvider>
                <ModalProvider>
                    <NavigationContainer>
                        <ScreenWrapperStatusContext.Provider value={SCREEN_WRAPPER_STATUS}>
                            <WorkspaceDistanceRatesTable
                                ratesData={[buildRow(GOVERNMENT_RATE)]}
                                policyID={POLICY_ID}
                                unit={CONST.CUSTOM_UNITS.DISTANCE_UNIT_MILES}
                                selectionEnabled={false}
                                selectedKeys={[]}
                                canWriteDistanceRates={false}
                                isDistanceRateTaxEnabled={false}
                                isGovernmentRateAutoUpdateEnabled={isGovernmentRateAutoUpdateEnabled}
                                onRowSelectionChange={jest.fn()}
                            />
                        </ScreenWrapperStatusContext.Provider>
                    </NavigationContainer>
                </ModalProvider>
            </PortalProvider>
        </ComposeProviders>
    );
}

/** The row names the icon in its accessibility label, so the label shows whether the icon is rendered. */
function queryRowWithAutoGeneratedIcon() {
    return screen.queryByLabelText(TestHelper.translateLocal('workspace.distanceRates.autoGeneratedRateTooltip'), {exact: false});
}

describe('WorkspaceDistanceRatesTable auto-generated rate icon', () => {
    beforeAll(() => {
        Onyx.init({keys: ONYXKEYS});
    });

    beforeEach(async () => {
        await act(async () => {
            await Onyx.set(ONYXKEYS.NVP_PREFERRED_LOCALE, CONST.LOCALES.EN);
        });
        jest.spyOn(useResponsiveLayoutModule, 'default').mockReturnValue(WIDE_LAYOUT);
    });

    afterEach(async () => {
        await act(async () => {
            await Onyx.clear();
        });
        jest.restoreAllMocks();
    });

    it('shows the icon on an unmodified government rate only while auto-update is on', async () => {
        // Given an unmodified government rate on a workspace with auto-update on
        const {rerender} = render(buildTable(true));
        await waitForBatchedUpdatesWithAct();

        // Then the rate is marked as auto-generated
        expect(queryRowWithAutoGeneratedIcon()).toBeOnTheScreen();

        // When the admin turns auto-update off while the table stays open
        rerender(buildTable(false));
        await waitForBatchedUpdatesWithAct();

        // Then the rate no longer claims to be auto-generated, since it won't be updated anymore
        expect(queryRowWithAutoGeneratedIcon()).toBeNull();

        // When the admin turns auto-update back on
        rerender(buildTable(true));
        await waitForBatchedUpdatesWithAct();

        // Then the icon comes back
        expect(queryRowWithAutoGeneratedIcon()).toBeOnTheScreen();
    });
});
