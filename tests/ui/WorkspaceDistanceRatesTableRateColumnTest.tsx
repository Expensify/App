import {render} from '@testing-library/react-native';

import {LocaleContextProvider} from '@components/LocaleContextProvider';
import type {TableColumn} from '@components/Table';
import WorkspaceDistanceRatesTable from '@components/Tables/WorkspaceDistanceRatesTable';
import type {DistanceRateTableItemData} from '@components/Tables/WorkspaceDistanceRatesTable/WorkspaceDistanceRatesTableRow';

import variables from '@styles/variables';

import CONST from '@src/CONST';

import React from 'react';

import {AUTO_GENERATED_RATE, buildDistanceRateTableItem} from '../utils/DistanceRatesTableTestUtils';
import waitForBatchedUpdatesWithAct from '../utils/waitForBatchedUpdatesWithAct';

let capturedColumns: Array<TableColumn<string, DistanceRateTableItemData>> = [];

// Only the columns the table hands to Table matter here, so Table records them instead of rendering the rows.
jest.mock('@components/Table', () => {
    const actual = jest.requireActual<Record<string, unknown>>('@components/Table');

    // Kept outside CapturingTable, which the React Compiler treats as a component: capturing render props into a module
    // variable is only for this test's assertions and would otherwise look like an impure component body.
    function captureColumns(columns: Array<TableColumn<string, DistanceRateTableItemData>>) {
        capturedColumns = columns;
    }

    function CapturingTable({columns}: {columns: Array<TableColumn<string, DistanceRateTableItemData>>}) {
        captureColumns(columns);
        return null;
    }

    return {...actual, __esModule: true, default: CapturingTable};
});

// jsdom has no canvas, so text measures as nothing unless a test hands the table a width.
const mockMeasureTextWidth = jest.fn<number | null, [string]>(() => null);

jest.mock('@libs/measureTextWidth', () => {
    const actual = jest.requireActual<Record<string, unknown>>('@libs/measureTextWidth');
    return {...actual, __esModule: true, default: (text: string) => mockMeasureTextWidth(text)};
});

jest.mock('@hooks/useResponsiveLayout', () => ({
    __esModule: true,
    default: () => ({shouldUseNarrowLayout: false, isMediumScreenWidth: false, isLargeScreenWidth: true}),
}));

// The gap (styles.gap2.gap) and the bolt icon the rate cell puts after an auto-generated rate.
const BOLT_WIDTH = variables.spacing2 + variables.iconSizeSmall;

const autoGeneratedItem = buildDistanceRateTableItem(AUTO_GENERATED_RATE);
const customItem = buildDistanceRateTableItem({customUnitRateID: 'custom', name: 'Custom', rate: 60, currency: CONST.CURRENCY.GBP, enabled: true});

async function renderTable(ratesData: DistanceRateTableItemData[], {canWriteDistanceRates = true}: {canWriteDistanceRates?: boolean} = {}) {
    render(
        <LocaleContextProvider>
            <WorkspaceDistanceRatesTable
                ratesData={ratesData}
                policyID="policy-1"
                selectionEnabled={false}
                selectedKeys={[]}
                canWriteDistanceRates={canWriteDistanceRates}
                isDistanceRateTaxEnabled={false}
                isGovernmentRateAutoUpdateEnabled
                onRowSelectionChange={jest.fn()}
            />
        </LocaleContextProvider>,
    );
    await waitForBatchedUpdatesWithAct();

    const rateColumn = capturedColumns.find((column) => column.key === 'rate');
    if (!rateColumn?.dynamicSizing) {
        throw new Error('Expected the rate column to be sized from its content');
    }
    return rateColumn.dynamicSizing;
}

describe('WorkspaceDistanceRatesTable rate column', () => {
    beforeEach(() => {
        capturedColumns = [];
        mockMeasureTextWidth.mockImplementation(() => null);
    });

    it('measures an auto-generated rate with its bolt and the edit button clearance, and a custom rate with its text only', async () => {
        // Given an auto-generated rate, whose cell shows a bolt, next to a custom rate
        const dynamicSizing = await renderTable([autoGeneratedItem, customItem]);

        // When the table measures each rate cell
        const [autoGeneratedContent] = dynamicSizing.getContentToMeasure(autoGeneratedItem);
        const [customContent] = dynamicSizing.getContentToMeasure(customItem);

        // Then only the bolt row makes room for the bolt and the edit button, so the button never covers the bolt
        expect(autoGeneratedContent?.trailingWidth).toBe(BOLT_WIDTH + variables.editableCellEditButtonClearance);
        expect(customContent?.trailingWidth).toBeUndefined();
        expect(dynamicSizing.extraWidth).toBe(variables.editableCellChromeWidth);
    });

    it('bounds the drag at the bolt and the edit button', async () => {
        // Given a table showing an auto-generated rate
        const dynamicSizing = await renderTable([autoGeneratedItem, customItem]);

        // When the table bounds the rate column's drag
        const {dragMinWidth} = dynamicSizing;

        // Then the drag stops at the padding, the bolt and the edit button, since only the rate text truncates
        expect(dragMinWidth).toBe(variables.editableCellChromeWidth + BOLT_WIDTH + variables.editableCellEditButtonClearance);
    });

    it('keeps the start of the amount visible at the drag bound, counted from its first digit', async () => {
        // Given an auto-generated rate with a long currency symbol, where text measures 10px per character
        mockMeasureTextWidth.mockImplementation((text) => text.length * 10);
        const canadianItem = {...autoGeneratedItem, formattedRate: 'CA$0.45 / km'};
        const dynamicSizing = await renderTable([canadianItem, customItem]);

        // When the table bounds the rate column's drag
        const {dragMinWidth} = dynamicSizing;

        // Then the bound also fits the symbol and the first characters of the amount, so the amount never disappears
        expect(mockMeasureTextWidth).toHaveBeenCalledWith('CA$0.45…');
        expect(dragMinWidth).toBe(variables.editableCellChromeWidth + 'CA$0.45…'.length * 10 + BOLT_WIDTH + variables.editableCellEditButtonClearance);
    });

    it('leaves no room for the edit button when the user cannot edit rates', async () => {
        // Given a read-only member, who never gets the edit button, viewing an auto-generated rate where text measures 10px per character
        mockMeasureTextWidth.mockImplementation((text) => text.length * 10);
        const dynamicSizing = await renderTable([autoGeneratedItem], {canWriteDistanceRates: false});

        // When the table measures the rate cell and bounds the drag
        const [autoGeneratedContent] = dynamicSizing.getContentToMeasure(autoGeneratedItem);
        const {dragMinWidth} = dynamicSizing;

        // Then only the bolt is measured after the text, and the drag still keeps the start of the amount before the bolt
        expect(autoGeneratedContent?.trailingWidth).toBe(BOLT_WIDTH);
        expect(dragMinWidth).toBe(variables.editableCellChromeWidth + '£0.45…'.length * 10 + BOLT_WIDTH);
    });

    it('keeps the usual drag bound when no rate shows the bolt', async () => {
        // Given a table with custom rates only, so no rate cell shows a bolt icon
        const dynamicSizing = await renderTable([customItem]);

        // When the table bounds the rate column's drag
        const {dragMinWidth} = dynamicSizing;

        // Then the column sets no drag bound of its own, so the table's default one applies
        expect(dragMinWidth).toBeUndefined();
    });
});
