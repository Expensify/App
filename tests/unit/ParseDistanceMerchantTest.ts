import DistanceRequestUtils from '@libs/DistanceRequestUtils';
import {translate as translateWithLocale} from '@libs/Localize';
import {getDistanceMerchantForTransaction} from '@libs/TransactionUtils/getUpdatedTransaction';
import parseDistanceMerchant, {getDistanceMerchantPrefix} from '@libs/TransactionUtils/parseDistanceMerchant';

import CONST from '@src/CONST';
import IntlStore from '@src/languages/IntlStore';

describe('parseDistanceMerchant', () => {
    beforeAll(async () => {
        await IntlStore.load(CONST.LOCALES.EN);
        await IntlStore.load(CONST.LOCALES.FR);
    });

    afterEach(() => {
        jest.restoreAllMocks();
    });

    describe.each([CONST.LOCALES.EN, CONST.LOCALES.FR])('formatter contract in %s', (locale) => {
        it.each([
            {rate: 50, unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_MILES, symbol: '$'},
            {rate: 1.5, unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_MILES, symbol: '$'},
            {rate: 123450, unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_KILOMETERS, symbol: '$'},
            {rate: 50, unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_KILOMETERS, symbol: undefined},
        ])('round-trips rate $rate and unit $unit with symbol $symbol', ({rate, unit, symbol}) => {
            // Given a label generated by the production formatter, without relying on a policy lookup
            jest.spyOn(IntlStore, 'getCurrentLocale').mockReturnValue(locale);
            const distance = 1.03;
            const merchant = getDistanceMerchantForTransaction({
                transaction: undefined,
                distanceInMeters: DistanceRequestUtils.convertToDistanceInMeters(distance, unit),
                unit,
                rate,
                currency: CONST.CURRENCY.USD,
                translate: (path, ...parameters) => translateWithLocale(locale, path, ...parameters),
                getCurrencySymbol: () => symbol,
            });

            // When the historical label is parsed with the saved structured distance, unit and currency
            const parsed = parseDistanceMerchant({merchant, distance, unit, currency: CONST.CURRENCY.USD, currencySymbol: symbol});

            // Then the exact rate survives the formatter/parser boundary, including fractional and large rates
            expect(parsed?.rate).toBeCloseTo(rate, 8);
            expect(`${getDistanceMerchantPrefix(distance, unit)}${parsed?.rateText}`).toBe(merchant);
        });
    });

    it.each(['UNKNOWN0.50 / mi', '$1,234.50 / mi', '$0.50 extra / mi', '$0.50 / km'])('does not infer a numeric rate from %s', (rateText) => {
        // Given a historical label with an unsupported currency, number format or unit
        const merchant = `1.03 mi @ ${rateText}`;

        // When parsing the complete rate value
        const parsed = parseDistanceMerchant({
            merchant,
            distance: 1.03,
            unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_MILES,
            currency: CONST.CURRENCY.USD,
            currencySymbol: '$',
        });

        // Then the raw snapshot remains available but the caller cannot treat the text as a verified numeric rate
        expect(parsed?.rateText).toBe(rateText);
        expect(parsed?.rate).toBeUndefined();
    });

    it('rejects a label that does not match the saved distance', () => {
        // Given a stale merchant from before the route was edited
        const merchant = '10.82 mi @ $0.50 / mi';

        // When it is checked against the new structured distance
        const parsed = parseDistanceMerchant({merchant, distance: 1.03, unit: CONST.CUSTOM_UNITS.DISTANCE_UNIT_MILES});

        // Then it cannot be mistaken for a snapshot of the new route
        expect(parsed).toBeUndefined();
    });
});
