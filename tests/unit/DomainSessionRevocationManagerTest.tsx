import {act, fireEvent, render, screen} from '@testing-library/react-native';

import DomainSessionRevocationManager from '@components/DomainSessionRevocationManager';
import Modal from '@components/Modal';

import * as API from '@libs/API';
import {SIDE_EFFECT_REQUEST_COMMANDS} from '@libs/API/types';

import ONYXKEYS from '@src/ONYXKEYS';
import type Response from '@src/types/onyx/Response';

import type {PropsWithChildren} from 'react';

import React from 'react';
import Onyx from 'react-native-onyx';

import getOnyxValue from '../utils/getOnyxValue';
import waitForBatchedUpdatesWithAct from '../utils/waitForBatchedUpdatesWithAct';

jest.mock('@components/Modal', () => jest.fn(({children}: PropsWithChildren) => children));
jest.mock('@hooks/useLocalize', () => () => ({translate: (key: string) => key}));
jest.mock('@libs/Navigation/Navigation', () => ({resetToAppRoot: jest.fn()}));

const completionHandle = 'ab'.repeat(32);
let request: jest.SpiedFunction<typeof API.makeRequestWithSideEffects>;

describe('Persistent domain revocation modal', () => {
    beforeAll(() => Onyx.init({keys: ONYXKEYS}));
    beforeEach(async () => {
        jest.restoreAllMocks();
        jest.clearAllMocks();
        request = jest.spyOn(API, 'makeRequestWithSideEffects').mockResolvedValue({jsonCode: 200, status: 'running'});
        await Onyx.clear();
        await waitForBatchedUpdatesWithAct();
    });

    it('restores a running receipt without starting another job and cannot be dismissed', async () => {
        // Given an operation saved before a reload
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});

        // When the global manager remounts and the user tries to dismiss it
        render(<DomainSessionRevocationManager />);
        await waitForBatchedUpdatesWithAct();
        jest.mocked(Modal).mock.lastCall?.[0].onClose?.();
        jest.mocked(Modal).mock.lastCall?.[0].onBackdropPress?.();

        // Then it remains blocking and only queries the existing receipt
        expect(screen.getByText('domain.members.sessionRevocation.runningBody')).toBeTruthy();
        expect(screen.queryByText('common.close')).toBeNull();
        expect(request).toHaveBeenCalledWith(SIDE_EFFECT_REQUEST_COMMANDS.GET_DOMAIN_SESSION_REVOCATION_STATUS, expect.objectContaining({completionHandle}));
        expect(request.mock.calls.every(([command]) => command === SIDE_EFFECT_REQUEST_COMMANDS.GET_DOMAIN_SESSION_REVOCATION_STATUS)).toBe(true);
        expect((await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION))?.status).toBe('running');
    });

    it('keeps success visible after removing credentials until Return to sign-in', async () => {
        // Given an authenticated actor and a running receipt
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        await Onyx.set(ONYXKEYS.SESSION, {authToken: 'revoked-token'});
        await Onyx.set(ONYXKEYS.CREDENTIALS, {autoGeneratedLogin: 'saved-login', autoGeneratedPassword: 'saved-password'});
        request.mockResolvedValue({jsonCode: 200, status: 'succeeded'});

        // When the status endpoint confirms success
        render(<DomainSessionRevocationManager />);
        await waitForBatchedUpdatesWithAct();

        // Then the same modal survives credential cleanup and its button only clears the receipt
        expect(screen.getByText('domain.members.sessionRevocation.succeededBody')).toBeTruthy();
        expect((await getOnyxValue(ONYXKEYS.SESSION))?.authToken).toBeFalsy();
        expect(await getOnyxValue(ONYXKEYS.CREDENTIALS)).toBeFalsy();
        const callsBeforeReturn = request.mock.calls.length;
        fireEvent.press(screen.getByText('domain.members.sessionRevocation.returnToSignIn'));
        await waitForBatchedUpdatesWithAct();
        expect(await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION)).toBeFalsy();
        expect(request).toHaveBeenCalledTimes(callsBeforeReturn);
    });

    it('discards an in-flight poll on unmount and schedules no further polling', async () => {
        // Given a status request still in flight
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        const pending = Promise.withResolvers<Response<never>>();
        request.mockReturnValue(pending.promise);
        const {unmount} = render(<DomainSessionRevocationManager />);
        await waitForBatchedUpdatesWithAct();

        // When the manager unmounts before the response arrives
        unmount();
        await act(async () => pending.resolve({jsonCode: 200, status: 'succeeded'}));
        await waitForBatchedUpdatesWithAct();
        act(() => jest.advanceTimersByTime(10000));

        // Then the stale response changes no state and creates no timer loop
        expect((await getOnyxValue(ONYXKEYS.DOMAIN_SESSION_REVOCATION))?.status).toBe('running');
        expect(request).toHaveBeenCalledTimes(1);
    });

    it('offers status-only recovery for an unavailable result without claiming success', async () => {
        // Given an unavailable completion result
        await Onyx.set(ONYXKEYS.DOMAIN_SESSION_REVOCATION, {completionHandle, status: 'running'});
        request.mockResolvedValue({jsonCode: 200, status: 'unavailable'});
        render(<DomainSessionRevocationManager />);
        await waitForBatchedUpdatesWithAct();

        // When the user checks again
        expect(screen.getByText('domain.members.sessionRevocation.unavailableBody')).toBeTruthy();
        expect(screen.queryByText('domain.members.sessionRevocation.succeededBody')).toBeNull();
        request.mockResolvedValue({jsonCode: 200, status: 'running'});
        fireEvent.press(screen.getByText('domain.members.sessionRevocation.checkStatus'));
        await waitForBatchedUpdatesWithAct();

        // Then the existing operation is queried without starting another job
        expect(screen.getByText('domain.members.sessionRevocation.runningBody')).toBeTruthy();
        expect(request.mock.calls.every(([command]) => command === SIDE_EFFECT_REQUEST_COMMANDS.GET_DOMAIN_SESSION_REVOCATION_STATUS)).toBe(true);
    });
});
