import updateSessionAuthTokens from '@libs/actions/Session/updateSessionAuthTokens';
import redirectToSignIn from '@libs/actions/SignInRedirect';
import HttpsError from '@libs/Errors/HttpsError';
import Log from '@libs/Log';
import {post} from '@libs/Network';
import {getAuthToken, getCredentials, setAuthToken, setIsAuthenticating} from '@libs/Network/NetworkStore';
import reauthenticate from '@libs/Reauthentication';
import trackAuthenticationError from '@libs/telemetry/trackAuthenticationError';

import CONST from '@src/CONST';
import ONYXKEYS from '@src/ONYXKEYS';

import Onyx from 'react-native-onyx';

import waitForBatchedUpdates from '../utils/waitForBatchedUpdates';

jest.mock('@libs/Network', () => ({post: jest.fn()}));
jest.mock('@libs/Network/NetworkStore', () => ({
    getAuthToken: jest.fn(),
    getCredentials: jest.fn(),
    hasReadRequiredDataFromStorage: jest.fn(() => Promise.resolve()),
    setAuthToken: jest.fn(),
    setIsAuthenticating: jest.fn(),
}));
jest.mock('@libs/telemetry/trackAuthenticationError', () => jest.fn());
jest.mock('@libs/actions/SignInRedirect', () => jest.fn());
jest.mock('@libs/actions/Session/updateSessionAuthTokens', () => jest.fn(() => Promise.resolve()));

describe('reauthenticate', () => {
    beforeAll(() => {
        Onyx.init({keys: ONYXKEYS});
        return waitForBatchedUpdates();
    });

    beforeEach(() => {
        jest.clearAllMocks();
        jest.mocked(getCredentials).mockReturnValue({autoGeneratedLogin: 'login', autoGeneratedPassword: 'password'});
        jest.mocked(getAuthToken).mockReturnValue('expiredToken');
    });

    test('should save the new authToken when the session did not change during re-authentication', async () => {
        // Given Authenticate succeeds while the session still holds the expired token
        jest.mocked(post).mockResolvedValueOnce({jsonCode: 200, authToken: 'newToken', encryptedAuthToken: 'newEncryptedToken'});

        // When the app reauthenticates
        const result = await reauthenticate('OpenApp');

        // Then the new token replaces the expired one so requests can resume
        expect(result).toEqual({wasSuccessful: true});
        expect(updateSessionAuthTokens).toHaveBeenCalledWith('newToken', 'newEncryptedToken');
        expect(setAuthToken).toHaveBeenCalledWith('newToken');
    });

    test('should compare against the current authToken when called without a flow-start token', async () => {
        // Given a caller outside the request middleware, such as the attachment image reauthenticator, which passes no arguments
        jest.mocked(post).mockResolvedValueOnce({jsonCode: 200, authToken: 'newToken', encryptedAuthToken: 'newEncryptedToken'});

        // When it reauthenticates while the session still holds the expired token
        const result = await reauthenticate();

        // Then the session is treated as unchanged and the new token is saved
        expect(result).toEqual({wasSuccessful: true});
        expect(post).toHaveBeenCalledTimes(1);
        expect(setAuthToken).toHaveBeenCalledWith('newToken');
    });

    test('should keep a copilot token the session switched to while Authenticate was in flight', async () => {
        // Given the user connects as a copilot while Authenticate for their own account is still in flight
        jest.mocked(post).mockImplementationOnce(() => {
            jest.mocked(getAuthToken).mockReturnValue('copilotToken');
            return Promise.resolve({jsonCode: 200, authToken: 'newToken', encryptedAuthToken: 'newEncryptedToken'});
        });

        // When the Authenticate response arrives
        const result = await reauthenticate('OpenApp');

        // Then the copilot session keeps its token and the network resumes with it
        expect(result).toEqual({wasSuccessful: true});
        expect(updateSessionAuthTokens).not.toHaveBeenCalled();
        expect(setAuthToken).not.toHaveBeenCalled();
        expect(setIsAuthenticating).toHaveBeenLastCalledWith(false);
    });

    test('should not authenticate a retry when the session switched during the previous attempt', async () => {
        // Given an earlier attempt of this re-authentication flow started with the expired token, and the user connected as a copilot before this retry
        jest.mocked(getAuthToken).mockReturnValue('copilotToken');

        // When the retry starts
        const result = await reauthenticate('OpenApp', 'expiredToken');

        // Then it keeps the copilot session instead of authenticating the original account and restoring it
        expect(result).toEqual({wasSuccessful: true});
        expect(post).not.toHaveBeenCalled();
        expect(setIsAuthenticating).toHaveBeenLastCalledWith(false);
    });

    test('should not sign out a session that switched while a failing Authenticate was in flight', async () => {
        // Given the user connects as a copilot while Authenticate for their own account is in flight, and Authenticate fails
        jest.mocked(post).mockImplementationOnce(() => {
            jest.mocked(getAuthToken).mockReturnValue('copilotToken');
            return Promise.resolve({jsonCode: CONST.JSON_CODE.NOT_AUTHENTICATED});
        });

        // When the Authenticate response arrives
        const result = await reauthenticate('OpenApp');

        // Then the failure belongs to the previous session, so the copilot session stays signed in
        expect(result).toEqual({wasSuccessful: true});
        expect(redirectToSignIn).not.toHaveBeenCalled();
    });

    test('should not sign out a session that switched while Authenticate failed with a non-retryable HTTP error', async () => {
        // Given the user connects as a copilot while Authenticate for their own account is in flight, and Authenticate fails with an HTTP error
        jest.mocked(post).mockImplementationOnce(() => {
            jest.mocked(getAuthToken).mockReturnValue('copilotToken');
            return Promise.reject(new HttpsError({message: 'Forbidden', status: '403'}));
        });

        // When the Authenticate error arrives
        const result = await reauthenticate('OpenApp');

        // Then the failure belongs to the previous session, so the copilot session stays signed in
        expect(result).toEqual({wasSuccessful: true});
        expect(redirectToSignIn).not.toHaveBeenCalled();
        expect(trackAuthenticationError).not.toHaveBeenCalled();
    });

    test('should not restore a session that was signed out while Authenticate was in flight', async () => {
        // Given the user signs out while Authenticate is in flight
        jest.mocked(post).mockImplementationOnce(() => {
            jest.mocked(getAuthToken).mockReturnValue(null);
            return Promise.resolve({jsonCode: 200, authToken: 'newToken', encryptedAuthToken: 'newEncryptedToken'});
        });

        // When the Authenticate response arrives
        const result = await reauthenticate('OpenApp');

        // Then the signed-out session stays signed out instead of receiving the new token
        expect(result).toEqual({wasSuccessful: false});
        expect(updateSessionAuthTokens).not.toHaveBeenCalled();
        expect(setAuthToken).not.toHaveBeenCalled();
    });

    test('should report an UNABLE_TO_RETRY Authenticate failure only once as network_retry', async () => {
        // Given Authenticate fails on a spotty connection and the network layer resolves with UNABLE_TO_RETRY
        jest.mocked(post).mockResolvedValueOnce({jsonCode: CONST.JSON_CODE.UNABLE_TO_RETRY});
        const alertSpy = jest.spyOn(Log, 'alert').mockImplementation(() => {});

        // When the app reauthenticates
        const result = reauthenticate('OpenApp');

        // Then the error still reaches the retry mechanism, but it is tracked once as a non-actionable network_retry
        // and not again as an unexpected_error, which would send a duplicate event to the Sentry error stream
        await expect(result).rejects.toThrow('Unable to retry Authenticate request');
        expect(trackAuthenticationError).toHaveBeenCalledTimes(1);
        expect(trackAuthenticationError).toHaveBeenCalledWith(expect.any(Error), expect.objectContaining({errorType: 'network_retry'}));
        expect(alertSpy).not.toHaveBeenCalled();
    });

    test('should still report an unexpected Authenticate failure as unexpected_error', async () => {
        // Given Authenticate rejects with an error that is not handled by any dedicated branch
        jest.mocked(post).mockRejectedValueOnce(new Error('Something broke'));
        const alertSpy = jest.spyOn(Log, 'alert').mockImplementation(() => {});

        // When the app reauthenticates
        const result = reauthenticate('OpenApp');

        // Then real failures keep going to the Sentry error stream so they stay visible
        await expect(result).rejects.toThrow('Something broke');
        expect(trackAuthenticationError).toHaveBeenCalledTimes(1);
        expect(trackAuthenticationError).toHaveBeenCalledWith(expect.any(Error), expect.objectContaining({errorType: 'unexpected_error'}));
        expect(alertSpy).toHaveBeenCalledTimes(1);
    });
});
